export function getOriginalWatchlistEntries() {
  return ORIGINAL_FILMS.map(film => ({
    tmdbId: film.tmdbId,
    source: 'original',
    originalId: film.slug,
    title: film.title,
    poster: film.posterPath,
    posterUrl: film.posterPath,
    overview: film.overview,
    releaseDate: String(film.releaseYear),
    mediaType: 'movie',
    addedAt: new Date(),
  }));
}

export function mergeMissingOriginalWatchlistMovies(existingMovies = [], seedMovies = getOriginalWatchlistEntries()) {
  const existingIds = new Set(existingMovies.flatMap(movie => [
    movie.originalId,
    Number.isInteger(movie.tmdbId) ? movie.tmdbId : null,
  ]).filter(value => value != null));
  return seedMovies.filter(movie => !existingIds.has(movie.originalId) && !existingIds.has(movie.tmdbId));
}
